def _is_boilerplate(text: str) -> bool:
    norm = re.sub(r"\s+", " ", text or "").strip()
    return any(p.search(norm) for p in _BOILERPLATE)


def build_blob(messages: list[dict], summary: str | None, rationale: str | None) -> str:
    """Единый текст для классификации: тексты сообщений + summary + rationale.
    Служебные авто-сообщения (приветствия, FAQ, запрос оценки и т.п.)
    отбрасываются целиком, чтобы не давать ложных срабатываний."""
    texts = [m.get("text", "") for m in (messages or [])
             if not _is_boilerplate(m.get("text", ""))]
    blob = " ".join(texts)
    return blob + " " + (summary or "") + " " + (rationale or "")


def classify(subcategory: str, blob: str) -> str | None:
    """Вернуть fine-bucket для подкатегории. None — если подкатегория не
    сегментируется; иначе имя специфичного bucket'а, а если ни один паттерн не
    сработал — общий (catch-all) bucket этой подкатегории."""
    rules = _COMPILED.get(subcategory)
    if rules is None:
        return None
    for name, pats in rules:
        for p in pats:
            if p.search(blob):
                return name
    return _FALLBACK[subcategory]
