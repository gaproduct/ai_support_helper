DDL = """
CREATE TABLE IF NOT EXISTS manual_subcategory_override (
    dialog_id   INTEGER PRIMARY KEY,
    subcategory TEXT NOT NULL
);
"""

UPSERT = """
INSERT INTO manual_subcategory_override (dialog_id, subcategory)
VALUES (:dialog_id, :subcategory)
ON CONFLICT (dialog_id) DO UPDATE SET subcategory = EXCLUDED.subcategory
"""

# Страховка от опечатки в id: размечать можно только диалоги своего периода.
# Дата берётся из tickets, отчёт считает период по ней, а не по dialogs.created_at.
CHECK = """
SELECT t.dialog_id, min(t.dialog_date), max(t.dialog_date)
FROM tickets t WHERE t.dialog_id = ANY(:ids) GROUP BY 1
"""


def main() -> None:
    s = get_session()
    s.execute(t(DDL))

    pairs = [(did, sub)
             for subs in TAXONOMY.values()
             for sub, ids in subs.items()
             for did in ids]
    ids = [p[0] for p in pairs]

    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SystemExit("диалог размечен дважды: %s" % dupes)

    rows = {r[0]: (r[1], r[2]) for r in s.execute(t(CHECK), {"ids": ids})}
    missing = [i for i in ids if i not in rows]
    if missing:
        raise SystemExit("нет таких диалогов: %s" % missing)

    a, b = PERIOD
    outside = [i for i in ids
               if not (a <= str(rows[i][0]) and str(rows[i][1]) <= b)]
    if outside:
        raise SystemExit("диалоги вне периода: %s" % outside)

    for did, sub in pairs:
        s.execute(t(UPSERT), {"dialog_id": did, "subcategory": sub})
    s.commit()

    print("размечено диалогов: %d" % len(pairs))
    for cat, subs in TAXONOMY.items():
        total = sum(len(v) for v in subs.values())
        print("\n%s  (%d)" % (cat, total))
        for sub, sids in sorted(subs.items(), key=lambda kv: -len(kv[1])):
            print("  %3d  %s" % (len(sids), sub))


if __name__ == "__main__":
    main()
